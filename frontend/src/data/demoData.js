/**
 * Export helpers: Generates genuine client-side JSON and CSV downloads
 */
export function exportReportJSON(scanData, vulnerabilities, components) {
  const report = {
    metadata: {
      generatedAt: new Date().toISOString(),
      tool: "SBOM Risk & Trust Auditor",
      version: "1.0.0",
      scanId: scanData.scanId,
      scanName: scanData.scanName,
      sbomFile: scanData.sbomFile,
      sbomFormat: scanData.sbomFormat,
      auditConfidence: scanData.sbomTrust.rating,
    },
    executiveSummary: {
      totalComponents: scanData.totalComponents,
      totalVulnerabilities: scanData.vulnerabilitiesCount,
      overallRiskScore: scanData.overallRisk.score,
      overallRiskLevel: scanData.overallRisk.level,
      sbomTrustScore: scanData.sbomTrust.score,
      criticalFindings: scanData.severityCounts.critical,
      highFindings: scanData.severityCounts.high,
      uncertainFindingsCount: scanData.uncertainFindings.length,
      note: "UNKNOWN DOES NOT MEAN SAFE. Confidence is bounded by SBOM metadata completeness.",
    },
    qualityAudit: scanData.qualityBreakdown,
    ntiaCompliance: scanData.ntiaMinimumElements,
    vulnerabilities: vulnerabilities,
    components: components,
  };

  const blob = new Blob([JSON.stringify(report, null, 2)], { type: "application/json" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = `sbom-risk-audit-${scanData.scanId}.json`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

export function exportReportCSV(vulnerabilities) {
  const headers = [
    "Priority",
    "Vulnerability ID",
    "CVE",
    "Package",
    "Installed Version",
    "Ecosystem",
    "Severity",
    "Risk Score",
    "Dependency Type",
    "Environment",
    "Confidence",
    "Fix Available",
    "Fixed Version",
    "Remediation Action"
  ];

  const rows = vulnerabilities.map(v => [
    v.priority,
    `"${v.id}"`,
    `"${v.cve || ''}"`,
    `"${v.package}"`,
    `"${v.installedVersion}"`,
    `"${v.ecosystem}"`,
    `"${v.severity}"`,
    v.riskScore,
    `"${v.dependencyType}"`,
    `"${v.environment}"`,
    `"${v.confidence}"`,
    v.fixAvailable ? "Yes" : "No",
    `"${v.fixedVersion || ''}"`,
    `"${(v.remediationCommand || '').replace(/"/g, '""')}"`
  ]);

  const csvContent = [headers.join(","), ...rows.map(r => r.join(","))].join("\n");
  const blob = new Blob([csvContent], { type: "text/csv;charset=utf-8;" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = "sbom-vulnerabilities-risk-audit.csv";
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
